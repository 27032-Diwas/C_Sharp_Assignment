namespace InventoryManager.EnumConstants;

/// <summary>
/// Contains all the enum related to menu options.
/// </summary>
public static class MenuConstants
{
    /// <summary>
    /// Contains main menu options.
    /// </summary>
    public enum MainMenu
    {
        /// <summary>
        /// Represent the option to exit the application.
        /// </summary>
        Exit,

        /// <summary>
        /// Represent the option to access the add product method.
        /// </summary>
        AddProduct,

        /// <summary>
        /// Represent the option to access the view products method.
        /// </summary>
        ViewProducts,

        /// <summary>
        /// Represent the option to access the search product method.
        /// </summary>
        SearchProduct,

        /// <summary>
        /// Represent the option to access the update product method.
        /// </summary>
        UpdateProduct,

        /// <summary>
        /// Represent the option to access the remove product method.
        /// </summary>
        RemoveProduct,
    }
}
