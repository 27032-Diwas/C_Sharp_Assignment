namespace InventoryManager.EnumConstants;

/// <summary>
/// Contains main menu options.
/// </summary>
public enum MainMenuEnum
{
    /// <summary>
    /// Represents the option to exit the application.
    /// </summary>
    Exit,

    /// <summary>
    /// Represents the option to access the add product method.
    /// </summary>
    AddProduct,

    /// <summary>
    /// Represents the option to access the view products method.
    /// </summary>
    ViewProducts,

    /// <summary>
    /// Represents the option to access the search product method.
    /// </summary>
    SearchProduct,

    /// <summary>
    /// Represents the option to access the update product method.
    /// </summary>
    UpdateProduct,

    /// <summary>
    /// Represents the option to access the remove product method.
    /// </summary>
    RemoveProduct,

    /// <summary>
    /// Represents the option to access the remove all product method.
    /// </summary>
    RemoveAllProducts,
}
