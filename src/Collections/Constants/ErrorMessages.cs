namespace Collections.Constants;

/// <summary>
/// Contains all error messages.
/// </summary>
public static class ErrorMessages
{
    /// <summary>
    /// Represents the messages displayed when user cancel the operation.
    /// </summary>
    public const string ProcessCancelled = "Process Cancelled";

    /// <summary>
    /// Represents the message displayed when user enters an invalid option.
    /// </summary>
    public const string InvalidOption = "ENTER A VALID OPTION";

