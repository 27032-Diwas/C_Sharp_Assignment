namespace Collections.Enums;

/// <summary>
/// Contains all the main menu options.
/// </summary>
public enum MainMenu
{
    /// <summary>
    /// Represents the option to exit the application.
    /// </summary>
    Exit,

    /// <summary>
    /// Represents the option to access list task.
    /// </summary>
    List,

    /// <summary>
    /// Represents the option to access stack task.
    /// </summary>
    Stack,

    /// <summary>
    /// Represents the option to access queue task.
    /// </summary>
    Queue,

    /// <summary>
    /// Represents the option to access dictionary task.
    /// </summary>
    Dictionary,
}
