    /// Represents the transaction amount.
    /// </summary>
    TransactionAmount,

    /// <summary>
    /// Represents the transaction category.
    /// </summary>
    TransactionCategory,

    /// <summary>
    /// Represents the transaction type.
    /// </summary>
    TransactionType,

    /// <summary>
    /// Represents the transaction description.
    /// </summary>
    TransactionDescription,
}
