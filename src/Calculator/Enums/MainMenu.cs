namespace Calculator.Enums;

/// <summary>
/// Contains all main menu options.
/// </summary>
public enum MainMenu
{
    /// <summary>
    /// Represents the option to exit the application.
    /// </summary>
    Exit,

    /// <summary>
    /// Represents the option to access addition operation.
    /// </summary>
    Addition,

    /// <summary>
    /// Represents the option to access subtraction operation.
    /// </summary>
    Subtraction,

    /// <summary>
    /// Represents the option to access multiplication operation.
    /// </summary>
    Multiplication,

    /// <summary>
    /// Represents the option to access division operation.
    /// </summary>
    Division,
}
